#!/usr/bin/env python3
"""Harvest the Skill Zodiac's graph from the design sources of
record (glyphs-of-ward-and-rune/build_tree.py + build_zodiac.py
+ tree_canopy.py) and bake the catalogue's unlock law
(your_files/zodiac-skill-unlocks.md, kept by Law) onto every
node: cost, pool, attunement gates, and named requirements.
Run: python3 scripts/gen-zodiac-data.py — writes
server/src/zodiacData.ts. The wheel page stays the design's
face; this file is the game's law."""
import json, os, re, sys

SRC_DIR = os.path.expanduser("~/workspace/glyphs-of-ward-and-rune")
os.chdir(SRC_DIR)
src = open(os.path.join(SRC_DIR, "build_zodiac.py")).read()
g = {"__file__": os.path.join(SRC_DIR, "build_zodiac.py")}
exec(src.split("def b64")[0], g)
nodes, edges = g["nodes"], g["edges"]

SPINES = {
    "w_key": ["w_thick", "w_answer", "w_rooted"],
    "b_key": ["b_wide", "b_mendwall", "b_thread"],
    "r_key": ["r_ink", "r_patient", "r_hum"],
}
CLUSTER_RE = re.compile(r"^(tide|sky|stone|root|fire)_(warden|binder|runewright)_([012n])$")

out = []
for n in nodes.values():
    nid = n["id"]
    kind = n["kind"]
    cost = 1
    if kind in ("keystone", "crown"):
        cost = 2
    if kind == "summon":
        cost = 3
    if nid == "b_muster":
        cost = 2
    gate = None
    m = CLUSTER_RE.match(nid)
    if m:
        gate = {"el": m.group(1), "level": 1}
    if kind == "crown" and n.get("el"):
        gate = {"el": n["el"], "level": 2}
    requires = list(SPINES.get(nid, []))
    if kind == "summon":
        god = nid.split("_", 1)[1]
        requires = [f"{slot}_{god}" for slot in ("ray", "hybW", "hybB", "hybR", "minor", "notA", "notB")]
    if nid == "b_muster":
        requires = ["w_escort", "b_pennant", "r_retinue"]
    if m and m.group(3) == "n":
        base = nid[:-1]
        requires = [base + "0", base + "1", base + "2"]
    out.append({
        "id": nid, "name": n["name"], "kind": kind, "sector": n["sector"],
        "x": n["x"], "y": n["y"], "effect": n.get("effect", ""), "syn": n.get("syn", ""),
        "el": n.get("el"), "pool": n.get("pool", "tree"), "cost": cost,
        "gate": gate, "requires": requires,
        "anyCore": nid == "c_hp2",
    })

out.sort(key=lambda z: z["id"])
edge_list = sorted([list(e) for e in edges])
ts = """/**
 * THE SKILL ZODIAC — the graph and its unlock law.
 * GENERATED by scripts/gen-zodiac-data.py from the design
 * sources of record (the tree + canopy data and Law's
 * catalogue of the first ninety-two). Do not edit by hand;
 * re-run the generator. 180 nodes, 237 roads.
 */
export interface ZodiacNode {
  id: string; name: string; kind: string; sector: string;
  x: number; y: number; effect: string; syn: string;
  el: string | null; pool: "tree" | "canopy"; cost: number;
  gate: { el: string; level: number } | null;
  requires: string[];
  /** The Long Watch's stem: any other heart-ring skill first. */
  anyCore: boolean;
}
export const ZODIAC_NODES: ZodiacNode[] = %s;
export const ZODIAC_EDGES: [string, string][] = %s;
export const ZODIAC_BY_ID = new Map(ZODIAC_NODES.map(n => [n.id, n]));
export const ZODIAC_ADJ: Record<string, string[]> = (() => {
  const adj: Record<string, string[]> = {};
  for (const n of ZODIAC_NODES) adj[n.id] = [];
  for (const [a, b] of ZODIAC_EDGES) { adj[a]?.push(b); adj[b]?.push(a); }
  return adj;
})();
""" % (json.dumps(out, indent=1), json.dumps(edge_list))
dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "server", "src", "zodiacData.ts")
with open(dest, "w") as f:
    f.write(ts)
print(f"wrote {dest}: {len(out)} nodes, {len(edge_list)} edges")
